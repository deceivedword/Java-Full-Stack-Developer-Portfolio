(function () {
    const ATRIBUTOS = ["placeholder", "alt", "aria-label", "title"];
    const limpiar = (t) => t.replace(/\s+/g, " ").trim();

    // Guarda el texto original en español de cada nodo para poder regresar a él
    const textos = [];
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
        acceptNode: (n) => n.parentElement.closest("script, style") ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT
    });
    while (walker.nextNode()) {
        const nodo = walker.currentNode;
        const clave = limpiar(nodo.nodeValue);
        if (EN[clave]) textos.push({ nodo, es: nodo.nodeValue, clave });
    }

    const atributos = [];
    document.querySelectorAll(ATRIBUTOS.map((a) => `[${a}]`).join(",")).forEach((el) => {
        ATRIBUTOS.forEach((a) => {
            const valor = el.getAttribute(a);
            if (valor && EN[limpiar(valor)]) atributos.push({ el, a, es: valor, clave: limpiar(valor) });
        });
    });

    const tituloEs = document.title;
    const boton = document.getElementById("langToggle");

    function aplicar(idioma) {
        const ingles = idioma === "en";
        textos.forEach(({ nodo, es, clave }) => {
            // Conserva los espacios alrededor para no pegar el texto a los íconos
            nodo.nodeValue = ingles ? es.replace(/\S[\s\S]*\S|\S/, EN[clave]) : es;
        });
        atributos.forEach(({ el, a, es, clave }) => el.setAttribute(a, ingles ? EN[clave] : es));
        document.title = ingles && EN[limpiar(tituloEs)] ? EN[limpiar(tituloEs)] : tituloEs;
        document.documentElement.lang = idioma;
        if (boton) boton.textContent = ingles ? "ES" : "EN";
    }

    let actual = "es";
    try { actual = localStorage.getItem("idioma") === "en" ? "en" : "es"; } catch (e) { }
    if (actual === "en") aplicar("en");

    if (boton) {
        boton.addEventListener("click", (e) => {
            e.preventDefault();
            actual = actual === "en" ? "es" : "en";
            aplicar(actual);
            try { localStorage.setItem("idioma", actual); } catch (err) { }
        });
    }
})();
